# Generates evoring_data.js from the approved round6 logo (tight ring variant): gold dots only (the Evolve O stays the app's raster).
import re
s=open('/workspace/evolve/evoai_logo/round6/EvoAI_original_O_spiral_ring_tight.svg').read()
g=re.search(r'<linearGradient[^>]*>.*?</linearGradient>',s,re.S).group(0)
d=re.findall(r'cx="([-\d.]+)" cy="([-\d.]+)" r="([\d.]+)" fill="url\(#g\)"(?: fill-opacity="([\d.]+)")?',s)
flat=[]
for x,y,r,o in d: flat+= [round(float(x)-1670),round(float(y)-1670),round(float(r)*2),round(float(o or 1)*100)]
open('evoring_data.js','w').write('// generated by tools/gen_evoring.py from round6/EvoAI_original_O_spiral_ring_tight.svg (%d gold dots; x,y relative to the O centre, 2*r, opacity%%)\nvar EVR_GRAD=%r;\nvar EVR_D=[%s];\n'%(len(d),g.replace('id="g"','id="evr-g"'),','.join(map(str,flat))))
print(len(d))
